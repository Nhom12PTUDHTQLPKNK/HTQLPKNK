IF OBJECT_ID(N'dbo.NHOMTHUOC', N'U') IS NULL
    CREATE TABLE dbo.NHOMTHUOC (
        MaNhomThuoc VARCHAR(10) NOT NULL PRIMARY KEY,
        TenNhomThuoc NVARCHAR(100) NOT NULL UNIQUE,
        MoTa NVARCHAR(500) NULL
    );
GO
IF OBJECT_ID(N'dbo.DANGBAOCHE', N'U') IS NULL
    CREATE TABLE dbo.DANGBAOCHE (
        MaDangBaoChe VARCHAR(10) NOT NULL PRIMARY KEY,
        TenDangBaoChe NVARCHAR(100) NOT NULL UNIQUE,
        MoTa NVARCHAR(255) NULL
    );
GO
IF OBJECT_ID(N'dbo.DUONGDUNG', N'U') IS NULL
    CREATE TABLE dbo.DUONGDUNG (
        MaDuongDung VARCHAR(10) NOT NULL PRIMARY KEY,
        TenDuongDung NVARCHAR(100) NOT NULL UNIQUE,
        MoTa NVARCHAR(255) NULL
    );
GO

IF OBJECT_ID(N'dbo.THUOC', N'U') IS NULL
    CREATE TABLE dbo.THUOC (
        MaThuoc VARCHAR(20) NOT NULL PRIMARY KEY,
        TenThuoc NVARCHAR(200) NOT NULL,
        HoatChatChinh NVARCHAR(200) NOT NULL,
        MaNhomThuoc VARCHAR(10) NOT NULL,
        MaDangBaoChe VARCHAR(10) NOT NULL,
        MaDuongDung VARCHAR(10) NOT NULL,
        NhaSanXuat NVARCHAR(150) NULL,
        NuocSanXuat NVARCHAR(100) NULL,
        GiaNhap DECIMAL(18,2) NOT NULL CONSTRAINT DF_THUOC_GiaNhap DEFAULT 0,
        QuyCachDongGoi NVARCHAR(150) NULL,
        MoTa NVARCHAR(1000) NULL,
        HinhAnh NVARCHAR(500) NULL,
        TrangThai BIT NOT NULL CONSTRAINT DF_THUOC_TrangThai DEFAULT 1,
        CONSTRAINT FK_THUOC_NHOMTHUOC FOREIGN KEY (MaNhomThuoc) REFERENCES dbo.NHOMTHUOC(MaNhomThuoc),
        CONSTRAINT FK_THUOC_DANGBAOCHE FOREIGN KEY (MaDangBaoChe) REFERENCES dbo.DANGBAOCHE(MaDangBaoChe),
        CONSTRAINT FK_THUOC_DUONGDUNG FOREIGN KEY (MaDuongDung) REFERENCES dbo.DUONGDUNG(MaDuongDung)
    );
GO

IF COL_LENGTH('dbo.THUOC', 'GiaNhap') IS NULL
    ALTER TABLE dbo.THUOC ADD GiaNhap DECIMAL(18,2) NOT NULL CONSTRAINT DF_THUOC_GiaNhap DEFAULT 0;
GO

